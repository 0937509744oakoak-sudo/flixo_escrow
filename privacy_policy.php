            <li><strong>ข้อมูล KYC:</strong> ตามความจำเป็นในการยืนยันตัวตน ป้องกันทุจริต และข้อกำหนดผู้ให้บริการ/กฎหมาย — หากถอนความยินยอม เราอาจจำกัดฟีเจอร์ที่เกี่ยวข้องและลบ/ทำให้ไม่สามารถระบุตัวตนได้เมื่อไม่มีฐานอื่นตามกฎหมาย</li>
            <li><strong>บันทึกความยินยอมและ Audit:</strong> เก็บเป็นหลักฐานการปฏิบัติตาม PDPA ตามระยะเวลาที่สมควร</li>
            <li><strong>ข้อมูลเซสชัน/ล็อกชั่วคราว:</strong> เก็บตามความจำเป็นด้านความปลอดภัยและการดูแลระบบ</li>
        </ul>
