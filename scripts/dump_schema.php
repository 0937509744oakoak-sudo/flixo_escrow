<?php
/**
 * Dump the live database structure to migrations/000_base_schema.sql.
 *
 * The repo has no CREATE TABLE for users, orders, products or messages — every
 * migration only ALTERs them — so a fresh database cannot currently be built
 * from source. Run this once against a known-good database and commit the
 * result, then a new environment is: 000_base_schema.sql, then run_migration.php.
 *
 * Usage:
 *   php scripts/dump_schema.php                  write migrations/000_base_schema.sql
 *   php scripts/dump_schema.php path/to/out.sql  write somewhere else
 *
 * Structure only — no rows are read, so this never copies user data.
 */
require_once __DIR__ . '/../includes/db.php';

$target = $argv[1] ?? __DIR__ . '/../migrations/000_base_schema.sql';

$tables = [];
$res = $conn->query('SHOW FULL TABLES WHERE Table_type = "BASE TABLE"');
while ($res && ($row = $res->fetch_array(MYSQLI_NUM))) {
    $tables[] = $row[0];
}
sort($tables, SORT_NATURAL);

if ($tables === []) {
    fwrite(STDERR, "No tables found in " . DB_NAME . " — is this the right database?\n");
    exit(1);
}

$out = "-- FLIXO Escrow — base schema\n";
$out .= "-- Generated by scripts/dump_schema.php from " . DB_NAME . " on " . date('Y-m-d H:i:s') . "\n";
$out .= "-- Structure only. Apply this first, then: php scripts/run_migration.php\n\n";
$out .= "SET FOREIGN_KEY_CHECKS = 0;\n\n";

foreach ($tables as $table) {
    if ($table === 'schema_migrations') {
        continue; // the migration runner creates its own ledger
    }
    $res = $conn->query('SHOW CREATE TABLE `' . str_replace('`', '``', $table) . '`');
    $row = $res ? $res->fetch_assoc() : null;
    if (!$row) {
        fwrite(STDERR, "Could not read structure for {$table}\n");
        exit(1);
    }
    $create = $row['Create Table'];
    // Make the dump replayable against a partially built database.
    $create = preg_replace('/^CREATE TABLE /', 'CREATE TABLE IF NOT EXISTS ', $create, 1);
    // Strip the current auto-increment counter so the file does not churn.
    $create = preg_replace('/\s+AUTO_INCREMENT=\d+/', '', $create);

    $out .= "-- ----------------------------------------------------------------\n";
    $out .= "-- {$table}\n";
    $out .= "-- ----------------------------------------------------------------\n";
    $out .= $create . ";\n\n";
}

$out .= "SET FOREIGN_KEY_CHECKS = 1;\n";

if (file_put_contents($target, $out) === false) {
    fwrite(STDERR, "Could not write {$target}\n");
    exit(1);
}

printf("Wrote %s (%d tables, %.1f KB)\n", realpath($target) ?: $target, count($tables), strlen($out) / 1024);
